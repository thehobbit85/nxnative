#!/usr/bin/env python3
"""Generate typed guest forwarding from an explicit policy list and pinned headers.

The list deliberately excludes WSI, callbacks and unimplemented extension families.
This does not turn arbitrary Vulkan symbols into guest entry points.
"""
import argparse
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
RESOURCES = '''
vkAllocateMemory vkFreeMemory vkMapMemory vkUnmapMemory vkFlushMappedMemoryRanges vkInvalidateMappedMemoryRanges
vkGetDeviceMemoryCommitment
vkCreateBuffer vkDestroyBuffer vkGetBufferMemoryRequirements vkGetBufferMemoryRequirements2 vkBindBufferMemory vkBindBufferMemory2
vkCreateBufferView vkDestroyBufferView
vkCreateImage vkDestroyImage vkGetImageMemoryRequirements vkGetImageMemoryRequirements2 vkBindImageMemory vkBindImageMemory2
vkGetImageSparseMemoryRequirements vkGetImageSparseMemoryRequirements2 vkGetImageSubresourceLayout
vkCreateImageView vkDestroyImageView vkCreateSampler vkDestroySampler
vkCreateDescriptorSetLayout vkDestroyDescriptorSetLayout vkCreateDescriptorPool vkDestroyDescriptorPool vkResetDescriptorPool
vkAllocateDescriptorSets vkFreeDescriptorSets vkUpdateDescriptorSets
vkCreatePipelineLayout vkDestroyPipelineLayout vkCreateRenderPass vkDestroyRenderPass vkCreateFramebuffer vkDestroyFramebuffer
vkCreateShaderModule vkDestroyShaderModule vkCreatePipelineCache vkDestroyPipelineCache vkGetPipelineCacheData vkMergePipelineCaches
vkCreateGraphicsPipelines vkDestroyPipeline
'''.split()
COMMANDS = '''
vkCreateCommandPool vkDestroyCommandPool vkResetCommandPool vkTrimCommandPool
vkAllocateCommandBuffers vkFreeCommandBuffers vkBeginCommandBuffer vkEndCommandBuffer vkResetCommandBuffer
vkCmdBeginRenderPass vkCmdEndRenderPass vkCmdBindPipeline vkCmdBindDescriptorSets vkCmdBindVertexBuffers vkCmdBindIndexBuffer
vkCmdSetViewport vkCmdSetScissor vkCmdDrawIndexed vkCmdDraw vkCmdPushConstants
vkCmdCopyBuffer vkCmdCopyBufferToImage vkCmdCopyImage vkCmdCopyImageToBuffer
vkCmdSetStencilCompareMask vkCmdSetStencilWriteMask vkCmdSetStencilReference
vkCmdClearColorImage vkCmdClearDepthStencilImage
vkCmdResetQueryPool vkCmdWriteTimestamp vkCmdBeginQuery vkCmdEndQuery vkCmdPipelineBarrier
vkQueueSubmit vkQueueBindSparse vkQueueWaitIdle vkDeviceWaitIdle
vkCreateFence vkDestroyFence vkResetFences vkGetFenceStatus vkWaitForFences
vkCreateQueryPool vkDestroyQueryPool vkGetQueryPoolResults vkCreateSemaphore vkDestroySemaphore
'''.split()
WAITS = {'vkQueueWaitIdle', 'vkDeviceWaitIdle', 'vkWaitForFences', 'vkGetQueryPoolResults'}
ALIASES = {name: name + 'KHR' for name in '''
vkGetBufferMemoryRequirements2 vkGetImageMemoryRequirements2 vkGetImageSparseMemoryRequirements2
vkBindBufferMemory2 vkBindImageMemory2
vkCreateDescriptorUpdateTemplate vkDestroyDescriptorUpdateTemplate vkUpdateDescriptorSetWithTemplate
vkTrimCommandPool
'''.split()}


def prototypes():
    header = (ROOT / 'dm/third_party/vulkan-headers/include/vulkan/vulkan_core.h').read_text()
    return {name: (ret, [' '.join(p.split()) for p in args.split(',')])
            for ret, name, args in re.findall(r'typedef (\w+) \(VKAPI_PTR \*PFN_(vk\w+)\)\((.*?)\);', header, re.S)}


def render(names):
    signatures = prototypes()
    out = ['// Generated by generate.py from the pinned Vulkan headers; edit the policy list, not this file.', '#include "guest_vk.h"', '']
    for name in names:
        ret, params = signatures[name]
        args = []
        for p in params:
            match = re.search(r'(\w+)(?:\[[^]]*\])?$', p)
            if not match: raise ValueError(p)
            args.append(match[1])
        packed = len(params) > 8
        if packed:
            out.append(f'typedef struct {{')
            for p in params:
                # Array parameters are pointers in a function signature.
                field = re.sub(r'(\w+)\[[^]]*\]$', r'*\1', p)
                out.append('    ' + field + ';')
            out.append(f'}} packet_{name};')
            out.append(f'GVK_PACKED({name}, GVK_DEVICE, {ret}, packet_{name}, ' + ', '.join(params) + ') {')
            out.append(f'    packet_{name} args = {{' + ', '.join('.' + a + ' = ' + a for a in args) + '};')
            out.append('    ' + ('return ' if ret != 'void' else '') + f'packed_enter_{name}(&args);')
            out.append('}')
            out.append(f'static {ret} packed_impl_{name}(const packet_{name} *args) {{')
        else:
            out.append(f'GVK({name}, GVK_DEVICE, {ret}, ' + ', '.join(params) + ') {')
        if 'pAllocator' in args and not packed: out.append('    (void)pAllocator; // Same host-allocation policy as the Apple frontend.')
        forwarded = ['NULL' if a == 'pAllocator' else ('args->' if packed else '') + a for a in args]
        if name in WAITS: out.append('    dm_thread_native_wait(1);')
        prefix = (ret + ' result = ') if name in WAITS else ('return ' if ret != 'void' else '')
        out.append('    ' + prefix + name + '(' + ', '.join(forwarded) + ');')
        if name in WAITS: out += ['    dm_thread_native_wait(0);', '    return result;']
        out.append('}')
        if name in ALIASES: out.append(f'GVK_ALIAS({ALIASES[name]}, {name}, GVK_DEVICE);')
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for filename, commands in [('resources_android.c', RESOURCES), ('commands_android.c', COMMANDS)]:
        target = HERE / filename
        result = render(commands)
        if args.check:
            if not target.exists() or target.read_text() != result: raise SystemExit(f'stale generated wrappers: {target}')
        else:
            target.write_text(result)


if __name__ == '__main__': main()
